export function searchHardwareBrands(
  query: string,
  categoryFilter: 'all' | 'dispenser' | 'atg' = 'all'
): readonly HardwareBrand[] {
  const clean = query.trim().toLowerCase();
  const pool =
    categoryFilter === 'dispenser'
      ? DISPENSER_BRANDS
      : categoryFilter === 'atg'
      ? ATG_PROBE_BRANDS
      : [...DISPENSER_BRANDS, ...ATG_PROBE_BRANDS];

  if (!clean) return pool;

  return pool.filter(
    (item) =>
      item.name.toLowerCase().includes(clean) ||
      (item.notes && item.notes.toLowerCase().includes(clean))
  );
}
